const runtimeGuildSchema = z.object({
  id: z.string().regex(/^\d{5,25}$/),
  name: z.string().min(1).max(100),
  icon: z.string().nullable(),
}).strict();

export const runtimeReportSchema = z.object({
  connected: z.boolean(),
  startedAt: z.string().datetime(),
  lastSync: z.string().datetime().nullable(),
  events: z.array(z.object({
    at: z.string().datetime(),
    code: z.enum(runtimeEventCodes),
  }).strict()).max(50),
  guilds: z.array(runtimeGuildSchema).max(500).default([]),
  /** FWU multi-bot: which application sent the report (absent = FWU, the historical bot). */
  profile: z.enum(["fwu", "guard", "fdpdlavoc", "suckme", "fisc"]).optional(),
}).strict();

/** Storage key: FWU keeps the historical "primary" row, each dedicated bot gets its own. */
export function runtimeStatusRowId(profile: RuntimeReport["profile"]): string {
  return !profile || profile === "fwu" ? "primary" : profile;
}

export type RuntimeReport = z.infer<typeof runtimeReportSchema>;
export type RuntimeStatus = RuntimeReport & { lastSeen: string };

